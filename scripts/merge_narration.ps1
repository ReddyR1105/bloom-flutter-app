param(
    [Parameter(Mandatory=$true)][string]$Narration,
    [string]$FFmpeg,
    [string]$Output = (Join-Path $PSScriptRoot 'Bloom_Final_Team_Presentation.mp4')
)
$ErrorActionPreference = 'Stop'
$video = Join-Path $PSScriptRoot 'Bloom_Final_23_Minute_Visuals.mp4'
if (!(Test-Path -LiteralPath $video)) { throw 'The silent visual recording is missing.' }
if (!(Test-Path -LiteralPath $Narration)) { throw 'Provide your actual recorded narration file.' }
if (Test-Path -LiteralPath $Output) { throw 'Choose a new output name to preserve an existing recording.' }
if (!$FFmpeg) {
    $existing = Get-Command ffmpeg -ErrorAction SilentlyContinue
    if ($existing) { $FFmpeg = $existing.Source }
    else {
        $localEncoder = Get-ChildItem -LiteralPath 'D:\ai-business-engine\bloom-submission-tools\imageio_ffmpeg\binaries' -Filter '*.exe' -ErrorAction SilentlyContinue | Select-Object -First 1
        if ($localEncoder) { $FFmpeg = $localEncoder.FullName }
    }
}
if (!$FFmpeg -or !(Test-Path -LiteralPath $FFmpeg)) { throw 'Pass the path to an existing FFmpeg executable using -FFmpeg.' }
& $FFmpeg -hide_banner -n -i $video -i $Narration -map '0:v:0' -map '1:a:0' -c:v copy -c:a aac -b:a 192k -af 'apad' -t 1380 -movflags '+faststart' $Output
if ($LASTEXITCODE -ne 0) { throw 'Narration merge failed. Review the encoder output.' }
Write-Output 'Merged your actual audio with the visual recording. Review the complete video for pacing, both voices, and any speech cut at the 23-minute endpoint.'
Write-Output 'The genuine ClickUp/task trace and other required student evidence must still be included. No voice or participation was generated by this script.'
